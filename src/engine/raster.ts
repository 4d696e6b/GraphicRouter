import { Resvg, initWasm } from "@resvg/resvg-wasm";
import { fontBuffers, wasmModule } from "graphicrouter:raster-assets";

const MAX_SVG_BYTES = 4_000_000;
const MAX_LONG_SIDE = 1600;
const MAX_PIXELS = 2_000_000;
const MAX_CANVAS_SIDE = 4000;

export const inspectionFontNote = "Inspection uses bundled SIL OFL Liberation Sans regular/bold, an Arial metric-compatible substitute. The editable blueprint and PowerPoint keep Arial; verify final Canva typography separately.";

export class RasterInspectionError extends Error {
  readonly code = "INSPECTION_FAILED";
  constructor(message: string) { super(message); this.name = "RasterInspectionError"; }
}

let initialized: Promise<void> | undefined;
let activeRenders = 0;
function initialize() {
  // Concurrent requests share initialization. A failed initialization is retriable.
  initialized ??= initWasm(wasmModule).catch(() => {
    initialized = undefined;
    throw new RasterInspectionError("The inspection renderer could not start. Retry inspection; the saved canvas is unchanged.");
  });
  return initialized;
}

/** Rasterize only SVG generated by the validated canvas engine, never user markup. */
export async function renderInspectionPng(svg: string, canvas: { width: number; height: number }): Promise<{ bytes: Uint8Array; width: number; height: number; fontNote: string }> {
  const { width, height } = canvas;
  if (![width, height].every((side) => Number.isSafeInteger(side) && side >= 1 && side <= MAX_CANVAS_SIDE)) {
    throw new RasterInspectionError("Inspection requires finite integer canvas dimensions between 1 and 4000 pixels.");
  }
  if (typeof svg !== "string" || !svg.startsWith("<svg ") || svg.length > MAX_SVG_BYTES || new TextEncoder().encode(svg).length > MAX_SVG_BYTES) {
    throw new RasterInspectionError("Inspection requires an engine-generated SVG smaller than 4 MB.");
  }
  // Defense in depth: the engine emits no executable markup, styles or external
  // resources. Keep the raster port offline even if its caller changes later.
  // Engine text is XML-escaped. Inspect only tags/attributes so visible copy such
  // as "Online = 45%" or "URL (optional)" cannot be mistaken for executable markup.
  const markup = svg.match(/<(?:[^>"']|"[^"]*"|'[^']*')*>/g)?.join("") ?? "";
  if (/<(?:script|foreignObject|style)\b|<!DOCTYPE|<!ENTITY|\bon\w+\s*=/i.test(markup)
    || /(?:href|xlink:href)\s*=\s*["'](?!data:image\/(?:png|jpeg);base64,)/i.test(markup)
    || /url\s*\(/i.test(markup)) {
    throw new RasterInspectionError("Inspection accepts only safe engine markup and bundled PNG/JPEG image data.");
  }
  const opening = svg.slice(0, svg.indexOf(">") + 1);
  if (!opening.includes(`width="${width}"`) || !opening.includes(`height="${height}"`) || !opening.includes(`viewBox="0 0 ${width} ${height}"`)) {
    throw new RasterInspectionError("Inspection dimensions must match the saved canvas SVG.");
  }

  const scale = Math.min(1, MAX_LONG_SIDE / Math.max(width, height), Math.sqrt(MAX_PIXELS / (width * height)));
  // Explicit output viewport bounds the pixel allocation. The original viewBox
  // preserves the exact element geometry and aspect ratio up to pixel rounding.
  const outputWidth = Math.max(1, Math.floor(width * scale));
  const outputHeight = Math.max(1, Math.floor(height * scale));
  const rasterSvg = svg.replace(/^<svg\b[^>]*>/, (tag) => tag
    .replace(/\bwidth="[^"]*"/, `width="${outputWidth}"`)
    .replace(/\bheight="[^"]*"/, `height="${outputHeight}"`))
    .replace(/font-family="Arial(?:, Helvetica, sans-serif)?"/g, 'font-family="Liberation Sans"');

  if (activeRenders >= 2) throw new RasterInspectionError("The inspection renderer is busy. Retry shortly; the saved canvas is unchanged.");
  activeRenders++;
  let renderer: InstanceType<typeof Resvg> | undefined;
  let rendered: ReturnType<InstanceType<typeof Resvg>["render"]> | undefined;
  try {
    await initialize();
    renderer = new Resvg(rasterSvg, {
      font: { fontBuffers, defaultFontFamily: "Liberation Sans", sansSerifFamily: "Liberation Sans" },
      textRendering: 2,
      shapeRendering: 2,
      imageRendering: 0,
    });
    rendered = renderer.render();
    if (rendered.width !== outputWidth || rendered.height !== outputHeight || rendered.width * rendered.height > MAX_PIXELS) {
      throw new Error("Unexpected raster dimensions.");
    }
    // Copy before releasing the WASM allocation; no live WASM memory escapes.
    const bytes = new Uint8Array(rendered.asPng());
    return { bytes, width: rendered.width, height: rendered.height, fontNote: inspectionFontNote };
  } catch {
    throw new RasterInspectionError("The canvas preview could not be rendered for inspection. Retry or simplify the composition; the saved canvas is unchanged.");
  } finally {
    rendered?.free();
    renderer?.free();
    activeRenders--;
  }
}
